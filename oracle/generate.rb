File.write("test/serialization_test.rb", <<~RUBY)
  # GENERATED by oracle/generate.rb: Crass's serialization test — real
  # stylesheets parsed with comments and hacks kept, and stringified back
  # to the same bytes.
  require "crass"

  SHEETS = [
  #{sheets.map { |name, css| "  [#{name.inspect}, #{css.inspect}]," }.join("\n")}
  ]

  SHEETS.each do |name, css|
    tree = Crass.parse(css, preserve_comments: true, preserve_hacks: true)
    out = Crass::Parser.stringify(tree)
    puts [name, css.length, tree.length, out == css].inspect
  end
  puts Crass::Parser.stringify(Crass.parse('@charset "utf-8";')).inspect
RUBY
