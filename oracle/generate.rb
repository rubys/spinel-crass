# Writes the test programs from the corpora in oracle/data: Simon Sapin's
# css-parsing-tests (the inputs Crass's own suite runs), a few real-world
# stylesheets Crass's serialization test round-trips, and the `style`
# values Loofah hands Crass. The inputs are embedded as literals so the
# compiled tests read no files; the EXPECTED output is not written here —
# `sh oracle/run.sh --regen` takes it from the real gem.
#
# Usage: ruby oracle/generate.rb   (from the repo root)
require "json"

DATA = File.join(__dir__, "data")

def inputs(name)
  JSON.parse(File.read(File.join(DATA, "#{name}.json"))).each_slice(2).map(&:first)
end

def literal_array(strings)
  "[\n" + strings.map { |s| "  #{s.inspect},\n" }.join + "]"
end

DUMP = <<~RUBY
  # A parse tree, printed the same way on both sides: every Hash with its
  # keys sorted, every leaf by inspect.
  def dump(v, out)
    if v.is_a?(Hash)
      out << "{"
      v.keys.sort_by { |k| k.to_s }.each do |k|
        out << k.to_s << "="
        dump(v[k], out)
        out << " "
      end
      out << "}"
    elsif v.is_a?(Array)
      out << "["
      v.each do |e|
        dump(e, out)
        out << ","
      end
      out << "]"
    else
      out << v.inspect
    end
    out
  end
RUBY

File.write("test/parse_test.rb", <<~RUBY)
  # GENERATED by oracle/generate.rb from css-parsing-tests
  # (component_value_list, declaration_list, one_declaration). Each input
  # is parsed the way Crass's own suite parses it, and the tree printed.
  require "crass"

  #{DUMP.strip}

  puts "-- parse_component_values"
  #{literal_array(inputs("component_value_list"))}.each do |css|
    puts dump(Crass::Parser.new(css).parse_component_values, +"")
  end

  puts "-- parse_declarations"
  #{literal_array(inputs("declaration_list") + inputs("one_declaration"))}.each do |css|
    parser = Crass::Parser.new(css)
    puts dump(parser.parse_declarations(parser.tokens, { strict: true }), +"")
  end
RUBY

